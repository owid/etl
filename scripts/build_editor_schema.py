"""Build the editor-only grapher chart-config schema from the published one.

ETL does not validate chart configs itself; the grapher admin API does that on upsert. This file only
gives editors typo and type checks inside `presentation.grapher_config` (`.meta.yml`) and multidim
view `config` / indicator `display` blocks: the overlays in `schemas/editor/` are mapped next to the
ETL schemas in `.vscode/settings.json` and `$ref` the file written here. Nothing in ETL reads it.

The published schema is adapted in two ways, both because ETL configs are not yet the final config:
- its top-level `required` is dropped, since `$schema` is stamped on upsert and never authored;
- any typed field also accepts a template string (Jinja, `{definitions...}`), which is rendered before
  the config reaches grapher. `oneOf` becomes `anyOf`, so a template matching several typed
  branches isn't rejected for matching more than one.

Run by `make .venv`. When the schema can't be fetched (offline), the previous file is kept, or an
open schema is written so the overlays still resolve.
"""

import json
from pathlib import Path
from typing import Any

import requests

from etl.config import DEFAULT_GRAPHER_SCHEMA
from etl.http import session
from etl.paths import SCHEMAS_DIR

OUTPUT = SCHEMAS_DIR / "editor" / "grapher-config.json"

# Values that are rendered before upsert: Jinja (`<% %>`, `<< >>`, `{{ }}`) and `{definitions.x}` refs.
TEMPLATE = {
    "type": "string",
    "pattern": r"<%|<<|\{\{|\{definitions|\{macros",
    "description": "Template, rendered before the config is upserted.",
}

# Keywords whose values are data, not subschemas.
_LITERAL_KEYS = {"enum", "const", "required", "default", "examples"}


def relax(node: Any) -> Any:
    """Return a copy of a schema node in which every typed field also accepts a template string."""
    if isinstance(node, list):
        return [relax(item) for item in node]
    if not isinstance(node, dict):
        return node
    out = {key: value if key in _LITERAL_KEYS else relax(value) for key, value in node.items()}
    if "oneOf" in out:
        out["anyOf"] = out.pop("oneOf")
    if "type" in out or "enum" in out or "const" in out:
        return {"anyOf": [out, TEMPLATE]}
    return out


def build_editor_schema(grapher_schema: dict[str, Any]) -> dict[str, Any]:
    """Adapt the published grapher schema for linting ETL-authored configs."""
    schema = {key: value for key, value in grapher_schema.items() if key not in ("required", "$id")}
    # The root stays a plain object schema, so an unknown key reports as "additional property".
    for key in ("properties", "$defs"):
        if key in schema:
            schema[key] = {name: relax(sub) for name, sub in schema[key].items()}
    # Multidim indicators carry a dimension's `display` block; give it a stable name for the overlay to `$ref`.
    display = grapher_schema.get("properties", {}).get("dimensions", {}).get("items", {}).get("properties", {})
    schema.setdefault("$defs", {})["dimensionDisplay"] = relax(display["display"]) if "display" in display else {}
    schema["description"] = (
        f"Generated by scripts/build_editor_schema.py from {DEFAULT_GRAPHER_SCHEMA}, for editor linting only."
    )
    return schema


def main() -> None:
    try:
        resp = session.get(DEFAULT_GRAPHER_SCHEMA, timeout=20)
        resp.raise_for_status()
        schema = build_editor_schema(resp.json())
    except requests.RequestException as e:
        if OUTPUT.exists():
            print(f"==> Could not fetch the grapher schema ({e}); keeping {OUTPUT.relative_to(Path.cwd())}")
            return
        print(f"==> Could not fetch the grapher schema ({e}); grapher configs won't be linted in the editor")
        schema = {"type": "object"}
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(json.dumps(schema, indent=2) + "\n")
    print(f"==> Built the editor schema for grapher configs from {DEFAULT_GRAPHER_SCHEMA}")


if __name__ == "__main__":
    main()
